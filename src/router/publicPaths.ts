/**
 * ЕДИНСТВЕННОЕ место, где собирается адрес публичной страницы.
 *
 * Сегодня адрес — просто «/слаг». Задел на языковые адреса (/en/…) состоит
 * ровно из трёх вещей, и это одна из них: когда владелец решит их включить,
 * правится эта функция, вызов makePublicRoutes('/en') в routes.tsx и список
 * маршрутов пререндера — больше нигде адреса руками не строятся.
 *
 * Слаги НЕ ПЕРЕВОДИМ намеренно: переведённый слаг навсегда лишает возможности
 * сменить язык, оставшись на той же странице, и ломает уже собранные ссылки.
 */
import type { Language } from '@/i18n/messages';

/**
 * Язык, живущий в адресе. Пока ни один: сайт на шести языках, но индексируется
 * по-русски (решение владельца), а язык хранится в localStorage.
 */
export const URL_LANGUAGES: Language[] = [];

export function publicPath(slug: string, lang?: Language): string {
  const prefix = lang && URL_LANGUAGES.includes(lang) ? `/${lang}` : '';
  return `${prefix}/${slug}`;
}
