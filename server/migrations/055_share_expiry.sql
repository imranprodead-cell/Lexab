-- Срок жизни публичной ссылки-отчёта (/share/:token).
--
-- Было (аудит 2026-08-03): у analysis_shares не было ни срока действия, ни
-- связи с удалением документа. Ссылка, однажды отправленная контрагенту,
-- работала ВЕЧНО и переживала «удалить навсегда» — резюме договора и все
-- находки оставались доступны всему интернету, а отозвать их через интерфейс
-- было уже нельзя (документ исчез вместе с кнопкой).
--
-- Теперь: 90 дней по умолчанию (столько же, сколько живёт ссылка на подпись),
-- проверка срока в GET /share/:token, и отзыв в DELETE /documents/:id.
-- Существующим ссылкам срок отсчитывается от даты создания — те, что старше
-- 90 дней, гаснут сразу; это осознанно: они и так утекли за пределы контроля.

ALTER TABLE analysis_shares ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;

UPDATE analysis_shares
   SET expires_at = created_at + interval '90 days'
 WHERE expires_at IS NULL;
