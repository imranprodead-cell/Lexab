-- Распознавание текста сканов и фото договоров (решение владельца 2026-10-17).
--
-- Скан и фото не несут текстового слоя: анализ на платном тарифе читает их
-- «глазами» (PDF уходит в модель целиком), а чат, поиск и повторный анализ
-- работают только с uploads.extracted_text — и для скана он был пуст. Теперь
-- при первом анализе дешёвая модель один раз переписывает текст со страниц
-- в extracted_text (зашифрованным, как и текст обычных файлов).
--
-- ocr_status отличает такой текст от извлечённого из файла:
--   NULL      — текст из самого файла (или его нет и распознавание не запускалось);
--   'pending' — распознаётся прямо сейчас;
--   'done'    — extracted_text распознан ИИ со скана: в чате об этом честно
--               предупреждается, а экспорт договора в файл его НЕ использует
--               (ошибка распознавания не должна уехать клиенту как «чистый текст»);
--   'failed'  — не вышло; следующий анализ или вопрос в чате попробует снова.
-- ocr_started_at снимает «вечный pending»: если сервер перезапустился посреди
-- распознавания, через 10 минут запуск разрешается заново.

ALTER TABLE uploads ADD COLUMN IF NOT EXISTS ocr_status TEXT
  CHECK (ocr_status IS NULL OR ocr_status IN ('pending', 'done', 'failed'));
ALTER TABLE uploads ADD COLUMN IF NOT EXISTS ocr_started_at TIMESTAMPTZ;
