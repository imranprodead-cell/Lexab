/**
 * Как найденные нормы попадают в контекст модели (чат, инструмент search_law и
 * проверка ответов evals/run-answers.ts — ОДНИ функции, чтобы проверка видела
 * ровно то же, что модель на сайте).
 *
 * Этап 3 (2026-11-09): у каждой нормы УЗ — вид акта (кодекс, закон, указ,
 * постановление Пленума), а перед нормами — правила выбора нормы при
 * расхождении актов. Каждое правило — пересказ конкретной статьи из базы
 * (с её [unit id]), ничего «от себя»: общего правила «спецзакон важнее ГК» в
 * праве Узбекистана нет — наоборот, ч.3 ст.3 ГК требует соответствия ГК.
 * LEGAL_RULES=off — прежний вид (сравнение «до/после»).
 */
import type { RetrievedChunk } from './types.ts';

/** Сколько символов текста нормы получает модель (полный текст — инструментом get_provision). */
export const CONTEXT_BODY_CHARS = 900;

/** Вид акта УЗ по типу документа корпуса — для пометки рядом с нормой. */
export function uzActKind(docType: string, title: string): string {
  if (/^Конституция/u.test(title)) return 'Конституция — высшая юридическая сила';
  switch (docType) {
    case 'code':
      return 'кодекс';
    case 'act':
      return 'закон';
    case 'decree':
      return 'указ Президента';
    case 'resolution':
      return 'постановление Президента';
    case 'plenum':
      return 'постановление Пленума — разъяснение судебной практики';
    default:
      return '';
  }
}

export const UZ_PRIORITY_RULES = `КАК ВЫБИРАТЬ НОРМУ, когда акты расходятся (Узбекистан; каждое правило — из текста закона; опираясь на правило, называй его норму):
1. Применяется акт с более высокой юридической силой; при равной силе — принятый позднее [lu_uz_5378968_st-18] (ст. 18 Закона «О нормативно-правовых актах»). Виды актов — ст. 6 того же Закона [lu_uz_5378968_st-6]; Конституция имеет высшую юридическую силу [lu_uz_5378968_st-8].
2. Противоречия и неясности в законодательстве во взаимоотношениях человека с государственными органами толкуются в пользу человека [lu_uz_5378968_st-18].
3. Нормы гражданского права в других законах должны соответствовать Гражданскому кодексу [lu_uz_111181_st-3] (ч. 3 ст. 3 ГК). Особое правило другого закона применяй там, где норма ГК это допускает («если иное не предусмотрено законом»), и называй обе нормы.
4. К трудовым и семейным отношениям ГК применяется, только когда они не урегулированы специальными законодательными актами [lu_uz_111181_st-2] (ч. 5 ст. 2 ГК): трудовые вопросы решай по Трудовому кодексу, а не по ГК.
5. Акты законодательства не могут ограничивать права потребителей и снижать гарантии их защиты, установленные Законом «О защите прав потребителей» [lu_uz_14643_st-2] (ст. 2).
6. Разъяснения Пленума Верховного суда обязательны для судов и органов, применяющих законодательство [lu_uz_5534928_st-25] (ст. 25 Закона «О судах»); называй пункт Пленума вместе с нормой, которую он разъясняет.`;

const rulesOn = () => process.env.LEGAL_RULES !== 'off';

/** Одна норма в контексте: [id] (вид акта) путь\nтекст. */
export function contextLine(h: RetrievedChunk, bodyChars = CONTEXT_BODY_CHARS): string {
  const kind = rulesOn() && h.actKind ? ` (${h.actKind})` : '';
  return `[${h.unitId}]${kind} ${h.breadcrumb}\n${h.body.slice(0, bodyChars)}`;
}

export function formatLegalContext(hits: RetrievedChunk[], jurisdiction?: string | null): string {
  if (!hits.length) return '';
  const body = hits.map((h) => contextLine(h)).join('\n---\n');
  return rulesOn() && jurisdiction === 'UZ' ? `${UZ_PRIORITY_RULES}\n===\n${body}` : body;
}
