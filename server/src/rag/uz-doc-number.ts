/**
 * Канонизация номера акта Президента РУз: «№ УП-6079», «UP 6079», «ПФ—60»,
 * «pq-4996» → «УП-6079» / «ПП-4996». Единственный источник истины для парсера
 * lex.uz И резолвера цитат — храним и ищем строго одну форму: кириллица,
 * верхний регистр, дефис-минус, без «№» и пробелов.
 *
 * Префиксы: УП/UP (Указ Президента) и узбекские формы ПФ/PF (Президент
 * Фармони); ПП/PP (Постановление Президента) и ПҚ/ПК/PQ (Президент Қарори).
 * «ПКМ-…» (Кабмин) намеренно НЕ матчится: после «ПК» стоит «М», а не цифра.
 */
const PREFIX_TO_CANON: Record<string, 'УП' | 'ПП'> = {
  УП: 'УП', UP: 'УП', ПФ: 'УП', PF: 'УП',
  ПП: 'ПП', PP: 'ПП', ПҚ: 'ПП', ПК: 'ПП', PQ: 'ПП',
};

export function normalizeUzDocNumber(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const cleaned = raw
    .replace(/№/g, '')
    .replace(/\s+/g, '')
    .replace(/[‐‑–—−]/g, '-')
    .toUpperCase();
  const m = cleaned.match(/^(УП|UP|ПФ|PF|ПП|PP|ПҚ|ПК|PQ)-?(\d{1,5})$/u);
  if (!m) return null;
  return `${PREFIX_TO_CANON[m[1]]}-${m[2]}`;
}
