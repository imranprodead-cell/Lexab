const BY_ID = new Map<string, Specialist>(SPECIALISTS.map((s) => [s.id, s]));

export function specialistById(id: string): Specialist | undefined {
  return BY_ID.get(id);
}

/** Памятки есть только для Узбекистана; SPECIALISTS=off — выключить (замер). */
export function specialistsOn(jurisdiction: string | null | undefined): boolean {
  return jurisdiction === 'UZ' && process.env.SPECIALISTS !== 'off';
}

const numbersOf = (list: string) => list.split(',').map((s) => s.trim()).filter(Boolean);
const unitIdOf = (act: ActKey, n: string) => `lu_uz_${SPECIALIST_ACTS[act]}_st-${n}`;

/** Все id норм памятки, в порядке карты. */
export function specialistUnitIds(spec: Specialist): string[] {
  return spec.map.flatMap((m) => m.refs.flatMap(([act, list]) => numbersOf(list).map((n) => unitIdOf(act, n))));
}

/**
 * Название акта для строки памятки — из заголовка в базе, механически:
 * «ЗРУ-1137-сон 21.04.2026. Об обществах…» → «Закон «Об обществах…» (№ ЗРУ-1137
 * от 21.04.2026)»; у кодексов убирается «Республики Узбекистан».
 */
export function shortActTitle(title: string, docType?: string | null): string {
  const t = title.replace(/\s+/g, ' ').trim();
  const m = /^(\S+?)-сон (\d{2}\.\d{2}\.\d{4})\.\s*(.+)$/u.exec(t);
  if (m) return `${docType === 'act' ? 'Закон ' : ''}«${m[3]}» (№ ${m[1]} от ${m[2]})`;
  return t.replace(/\s+Республики Узбекистан/u, '');
}

const ANSWER_SHAPE =
  '1) Короткий вывод — одно-два предложения. 2) Что говорит закон — по каждому вопросу, со ссылкой на статью и акт. ' +
  '3) Что это значит в ситуации пользователя (если фактов не хватает — по вариантам). 4) Что делать — по шагам, со сроками из норм. ' +
  '5) Чего не хватает для точного ответа — в конце, коротко.';

/** Памятка целиком уходит модели — держим её короткой (проверяет specialists-check). */
export const MAX_GUIDE_CHARS = 12_000;

export interface RenderedGuide {
  text: string;
  /** Нормы, попавшие в памятку (действуют сегодня) — для ссылок в Sources. */
  units: { unitId: string; breadcrumb: string }[];
  /** Нормы карты, которых в базе нет или которые не действуют, — в памятку не попали. */
  missing: string[];
}

/**
 * Текст памятки для модели. Заголовки статей и названия актов — из базы
 * (один запрос); норма, которой нет или которая не действует сегодня,
 * пропускается. Памятка — карта, а не текст закона: правил в ней нет.
 */
export async function renderGuide(db: Db, spec: Specialist): Promise<RenderedGuide> {
  const ids = specialistUnitIds(spec);
  const day = new Date().toISOString().slice(0, 10);
  const res = await db.query<{ id: string; heading: string | null; breadcrumb: string; title: string; doc_type: string | null }>(
    `SELECT u.id, u.heading, u.breadcrumb, d.title, d.doc_type
     FROM legal_units u JOIN legal_documents d ON d.id = u.document_id
     WHERE u.id = ANY($1::text[])
       AND (u.valid_from IS NULL OR u.valid_from <= $2::date)
       AND (u.valid_to   IS NULL OR u.valid_to   >= $2::date)`,
    [ids, day],
  );
  const rows = new Map(res.rows.map((r) => [r.id, r]));
  const missing = ids.filter((id) => !rows.has(id));
  if (missing.length) console.warn(`[specialists] ${spec.id}: норм нет в базе или не действуют — пропущены: ${missing.join(', ')}`);

  const units: RenderedGuide['units'] = [];
  const topics: string[] = [];
  for (const m of spec.map) {
    const lines: string[] = [];
    for (const [act, list] of m.refs) {
      // Название акта — одной строкой над его статьями (не повторяем в каждой).
      const found = numbersOf(list)
        .map((n) => ({ n, row: rows.get(unitIdOf(act, n)) }))
        .filter((x): x is { n: string; row: NonNullable<typeof x.row> } => !!x.row);
      if (!found.length) continue;
      lines.push(`  ${shortActTitle(found[0].row.title, found[0].row.doc_type)}:`);
      for (const { n, row } of found) {
        units.push({ unitId: row.id, breadcrumb: row.breadcrumb });
        const heading = (row.heading ?? '').replace(/\s+/g, ' ').trim();
        lines.push(`    [${row.id}] ст. ${n}${heading ? ` — ${heading}` : ''}`);
      }
    }
    if (lines.length) topics.push(`• ${m.topic}\n${lines.join('\n')}`);
  }

  const text = [
    `TASK GUIDE «${spec.title}» — a map of WHERE the rules are in Lexab's verified database. It is NOT the law: it holds no rules, figures or deadlines, and an article's heading is not its rule.`,
    'HOW TO USE: pick the topics the user\'s question turns on and open those provisions with get_provision (unit_id = the id in square brackets) — all in ONE step, usually 3–8 provisions, not the whole list; skip the ones the legal context already gives in full. Take every rule, figure and deadline from the text you opened, and cite only provisions whose text you have read. A point the map does not cover: search_law. Write the answer in the user\'s language, as usual.',
    '',
    'WHAT THE ANSWER DEPENDS ON (do not stop to ask: if the user has not said, answer for each realistic variant or state your assumption, and list what is missing at the end):',
    ...spec.ask.map((a) => `- ${a}`),
    '',
    'WHERE THE RULES ARE:',
    ...topics,
    '',
    'CHECK BEFORE YOU ANSWER (each line points to the text that decides it):',
    ...spec.check.map((c) => `- ${c}`),
    '',
    `ANSWER SHAPE: ${ANSWER_SHAPE}`,
  ].join('\n');
  return { text, units, missing };
}
